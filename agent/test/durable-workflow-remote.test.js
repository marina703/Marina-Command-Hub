async function phase8_approveV2() {
  log("Phase 8", "Reading v2 approval record to get the real payload hash, then approving v2...");
  const approvals = await callDurable("GET", "/api/durable/approvals", {
    token: manifest.ownerAccessToken, query: { workspaceId: manifest.workspaceId },
  });
  assertOk(approvals, 200, "listApprovals");
  const v2Approval = approvals.body.approvals.find(
    (a) => a.actionTarget === manifest.revisionPlanId && a.actionType === "plan.approve"
  );
  assert.ok(v2Approval, "v2 plan approval record must exist");
  const realHash = v2Approval.payloadHash;
  const res = await callDurable("POST", "/api/durable/plans/decide", {
    body: {
      workspaceId: manifest.workspaceId,
      planId: manifest.revisionPlanId,
      decision: "approve",
      payloadHash: realHash,
    },
    token: manifest.ownerAccessToken,
  });
  assertOk(res, 200, "approveV2");
  assert.equal(res.body.plan.status, "approved");
  manifest.approvedPlanId = manifest.revisionPlanId;
  manifest.approvedPlanPayloadHash = realHash;
  log("Phase 8", "Plan v2 approved (id=" + manifest.approvedPlanId + ").");
}

