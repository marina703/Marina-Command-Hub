function makeReqRes({ method, url, headers = {}, body }) {
  let emittedEnd = false;
  const data = body == null ? "" : (typeof body === "string" ? body : JSON.stringify(body));
  const stream = new Readable({
    read() {
      if (!emittedEnd) {
        emittedEnd = true;
        this.push(data);
        this.push(null);
      }
    },
  });
  stream.method = method;
  stream.url = url;
  stream.headers = { "content-type": "application/json", ...headers };
  let statusCode = null;
  let bodyOut = null;
  let headersOut = {};
  const res = {
    headersSent: false,
    writeHead(code, hdrs) {
      statusCode = code;
      if (hdrs) headersOut = Object.assign({}, headersOut, hdrs || {});
      return this;
    },
    end(payload) {
      this.headersSent = true;
      bodyOut = payload == null ? "" : String(payload);
      return this;
    },
  };
  return {
    req: stream,
    res,
    capture() {
      const parsed = bodyOut ? (function () { try { return JSON.parse(bodyOut); } catch (_) { return bodyOut; } })() : null;
      return { status: statusCode, headers: headersOut, body: parsed };
    },
  };
}

async function callDurable(method, urlPath, opts) {
  opts = opts || {};
  const { body, token, query } = opts;
  let u = urlPath;
  if (query && Object.keys(query).length) {
    const sp = new URLSearchParams();
    for (const k of Object.keys(query)) {
      const v = query[k];
      if (v !== undefined && v !== null) sp.set(k, String(v));
    }
    const qs = sp.toString();
    if (qs) u += "?" + qs;
  }
  const headers = {};
  if (token) headers.authorization = "Bearer " + token;
  const handle = makeReqRes({ method, url: u, headers, body });
  await durableRoutes.handleDurable(handle.req, handle.res, new URL(u, "http://localhost"));
  return handle.capture();
}

function assertOk(result, expectedStatus, ctx) {
  if (result.status !== expectedStatus) {
    throw new Error("[" + ctx + "] expected status " + expectedStatus + ", got " + result.status + ": " + JSON.stringify(result.body));
  }
  if (result.body && result.body.ok === false) {
    throw new Error("[" + ctx + "] response.ok=false: " + result.body.message);
  }
}

function assertStatus(result, expected, ctx) {
  if (result.status !== expected) {
    throw new Error("[" + ctx + "] expected status " + expected + ", got " + result.status + ": " + JSON.stringify(result.body));
  }
}

