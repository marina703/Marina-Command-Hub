async function phase2_createUsers() {
  log("Phase 2", "Creating labelled owner + non-member Auth test users...");
  const ownerRes = await serviceClient.auth.admin.createUser({
    email: manifest.ownerEmail, password: manifest.password, email_confirm: true,
  });
  if (ownerRes.error) throw new Error("Owner create failed: " + ownerRes.error.message);
  manifest.ownerUserId = ownerRes.data.user.id;
  log("Phase 2", "Owner created: " + manifest.ownerEmail + " (" + manifest.ownerUserId + ")");

  const nmRes = await serviceClient.auth.admin.createUser({
    email: manifest.nonMemberEmail, password: manifest.password, email_confirm: true,
  });
  if (nmRes.error) throw new Error("Non-member create failed: " + nmRes.error.message);
  manifest.nonMemberUserId = nmRes.data.user.id;
  log("Phase 2", "Non-member created: " + manifest.nonMemberEmail + " (" + manifest.nonMemberUserId + ")");

  const anon = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, { auth: { persistSession: false } });
  const ownerSession = await anon.auth.signInWithPassword({
    email: manifest.ownerEmail, password: manifest.password,
  });
  if (ownerSession.error) throw new Error("Owner sign-in failed: " + ownerSession.error.message);
  manifest.ownerAccessToken = ownerSession.data.session.access_token;
  const nmSession = await anon.auth.signInWithPassword({
    email: manifest.nonMemberEmail, password: manifest.password,
  });
  if (nmSession.error) throw new Error("Non-member sign-in failed: " + nmSession.error.message);
  manifest.nonMemberAccessToken = nmSession.data.session.access_token;
}

