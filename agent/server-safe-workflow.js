/* ============================================================
   MarinaAI — Safe Internal Workflow (Providerless)

   One deliberately bounded execution path, labelled truthfully
   as "Safe workflow preview" in the UI and events. It is
   deterministic, side-effect-free outside the MarinaAI database
   and private artifact bucket, and is not browser automation,
   shell execution, web retrieval, model inference, message
   sending, deployment, or tool dispatch.

   The flow is synchronous and bounded. It creates:
     - one durable run
     - an ordered timeline of events
     - a private artifact with provenance
     - an audit event

   It is gated by:
     - task/workspace authorization (server-side, RLS)
     - plan approval bound to plan version + payload hash
     - status-transition validity
     - configured time/budget limits
     - idempotency / duplicate active-run protection
   ============================================================ */

const CRYPTO = require("crypto");
const planner = require("./server-planner");
const sm = require("./server-state-machine");

const WORKFLOW_ID = "safe-internal";
const WORKFLOW_LABEL = "Safe workflow preview";
const ARTIFACT_KIND = "plan-brief";
const ARTIFACT_MEDIA = "text/markdown";

const MAX_INPUT_BYTES = 100 * 1024;        // 100KB input cap
const MAX_OUTPUT_BYTES = 200 * 1024;       // 200KB output cap
const DEFAULT_TIMEOUT_MS = 8000;           // 8s server-side budget

function newCorrelationId() {
  return CRYPTO.randomBytes(8).toString("hex");
}

function hashString(s) {
  return CRYPTO.createHash("sha256").update(String(s)).digest("hex");
}

function buildBrief(task, plan) {
  const steps = (plan.steps || [])
    .map(
      (s, i) =>
        `### ${i + 1}. ${s.title}\n` +
        `- **Purpose**: ${s.purpose || ""}\n` +
        `- **Tool class**: ${s.toolClass || "safe-internal"}\n` +
        `- **Risk tier**: ${s.riskTier || "low"}\n` +
        `- **Requires approval**: ${s.requiresApproval ? "yes" : "no"}\n` +
        `- **Expected output**: ${s.expectedOutput || ""}`,
    )
    .join("\n\n");
  const assumptions = (plan.assumptions || [])
    .map((a) => `- ${a}`)
    .join("\n");
  const risks = (plan.risks || [])
    .map((r) => `- ${r}`)
    .join("\n");

  return [
    `# ${task.title || "Plan brief"}`,
    "",
    `_Generated by ${planner.PLANNER_LABEL} via ${WORKFLOW_LABEL}._`,
    "",
    `## Desired outcome`,
    task.desiredOutcome || "(none provided)",
    "",
    `## Plan summary`,
    plan.summary || "(no summary)",
    "",
    `## Plan version`,
    `v${plan.version} (${plan.status})`,
    "",
    `## Assumptions`,
    assumptions || "- (none)",
    "",
    `## Risks`,
    risks || "- (none)",
    "",
    `## Steps`,
    steps || "- (no steps)",
    "",
    `## Provenance`,
    `- Plan id: ${plan.id}`,
    `- Plan payload hash: ${plan.payloadHash || ""}`,
    `- Task id: ${task.id}`,
    `- Generated: ${new Date().toISOString()}`,
    `- Workflow: ${WORKFLOW_ID}`,
    `- Provider: ${plan.provider || planner.PLANNER_ID}`,
  ].join("\n");
}

function classifyApproval(approval) {
  if (!approval) return { ok: false, reason: "missing" };
  if (approval.status !== "approved") return { ok: false, reason: `status=${approval.status}` };
  if (approval.expiresAt && new Date(approval.expiresAt).getTime() < Date.now()) {
    return { ok: false, reason: "expired" };
  }
  return { ok: true };
}

/**
 * Validate the plan-approval binding against the current plan.
 * If the plan's payloadHash no longer matches, the prior approval
 * is invalidated (the plan was revised).
 */
function validatePlanApproval({ plan, approval, currentPayloadHash }) {
  if (!plan) return { ok: false, reason: "plan not found" };
  if (plan.status !== "approved") {
    return { ok: false, reason: `plan_status=${plan.status}` };
  }
  if (currentPayloadHash && plan.payloadHash && plan.payloadHash !== currentPayloadHash) {
    return { ok: false, reason: "plan_payload_changed" };
  }
  const a = classifyApproval(approval);
  if (!a.ok) return { ok: false, reason: `approval_${a.reason}` };
  if (approval.taskId && plan.taskId && approval.taskId !== plan.taskId) {
    return { ok: false, reason: "approval_task_mismatch" };
  }
  if (approval.payloadHash && plan.payloadHash && approval.payloadHash !== plan.payloadHash) {
    return { ok: false, reason: "approval_payload_mismatch" };
  }
  return { ok: true };
}

/**
 * Run the safe internal workflow.
 *
 * @param {object} ctx - { supabase, task, plan, planApproval, actor }
 * @returns {Promise<{ok, run, artifact, events, message?}>}
 */
async function runSafeWorkflow(ctx) {
  const startMs = Date.now();
  const correlationId = newCorrelationId();
  const { supabase, task, plan, planApproval, actor } = ctx;

  // ── Pre-flight: validate state-machine transition (task -> queued) ──
  try {
    sm.assertTransition("task", task.status, "queued", actor);
  } catch (err) {
    return {
      ok: false,
      message: `Cannot start run: ${err.message}`,
      failureClassification: "invalid_state",
      correlationId,
    };
  }

  // ── Validate plan approval binding ──
  const planCheck = validatePlanApproval({
    plan,
    approval: planApproval,
    currentPayloadHash: plan.payloadHash,
  });
  if (!planCheck.ok) {
    return {
      ok: false,
      message: `Plan approval invalid: ${planCheck.reason}`,
      failureClassification: "policy_blocked",
      correlationId,
    };
  }

  // ── Idempotency / duplicate active run check ──
  const dup = await supabase.findActiveRunForTaskInDb(task.workspaceId, task.id);
  if (dup && dup.ok && dup.run) {
    return {
      ok: false,
      message: "An active run already exists for this task.",
      failureClassification: "duplicate",
      correlationId,
    };
  }

  // ── Bounded output & time budget preflight ──
  const timeLimit = task.timeLimitSeconds && task.timeLimitSeconds > 0
    ? Math.min(task.timeLimitSeconds * 1000, DEFAULT_TIMEOUT_MS * 4)
    : DEFAULT_TIMEOUT_MS;

  // ── Create durable run ──
  const runResult = await supabase.createRunInDb({
    workspaceId: task.workspaceId,
    taskId: task.id,
    planId: plan.id,
    attemptCount: 1,
    provider: plan.provider || planner.PLANNER_ID,
    toolSummary: WORKFLOW_ID,
  });
  if (!runResult.ok) return { ok: false, message: runResult.message, correlationId };

  const run = runResult.run;

  // Helper to persist an event with auto-sequence
  async function recordEvent(event, summary, metadata = {}, actorName = "system") {
    const seq = await supabase.nextRunEventSequence(run.id);
    const seqNum = seq.ok ? seq.sequence : 0;
    return supabase.createRunEventInDb({
      workspaceId: task.workspaceId,
      runId: run.id,
      taskId: task.id,
      sequence: seqNum,
      event,
      summary,
      metadata: { ...metadata, correlationId },
      actor: actorName,
    });
  }

  // 1. run queued
  await recordEvent(
    "run.queued",
    `Run ${run.id} queued for plan v${plan.version}`,
    { planVersion: plan.version, planId: plan.id },
    "system",
  );

  // 2. run started (transition queued -> active)
  const started = await supabase.updateRunStatusInDb(run.id, "active", { skipStartedAt: false });
  if (!started.ok) {
    await supabase.updateRunStatusInDb(run.id, "failed", { failureClassification: "internal_error" });
    return { ok: false, run, message: started.message, correlationId };
  }
  await recordEvent(
    "run.started",
    `${WORKFLOW_LABEL} started`,
    { workflow: WORKFLOW_ID },
    "system",
  );

  // ── Cooperative cancellation check before artifact commit ──
  // (Future durable queue would observe this from the database)
  const stillActive = await supabase.getRunInDb(run.id);
  if (stillActive && stillActive.ok && stillActive.run.status === "cancelled") {
    await recordEvent("run.cancelled", "Run cancelled before artifact commit", {}, "system");
    return {
      ok: false,
      run: stillActive.run,
      message: "Run was cancelled before completion.",
      failureClassification: "cancelled",
      correlationId,
    };
  }

  // ── Generate the bounded Markdown brief ──
  let content;
  try {
    content = buildBrief(task, plan);
  } catch (err) {
    await supabase.updateRunStatusInDb(run.id, "failed", { failureClassification: "internal_error" });
    await recordEvent("run.failed", `Artifact generation error: ${err.message}`, { error: err.message }, "system");
    return { ok: false, run, message: "Artifact generation failed.", correlationId };
  }

  if (Buffer.byteLength(content, "utf8") > MAX_OUTPUT_BYTES) {
    await supabase.updateRunStatusInDb(run.id, "failed", { failureClassification: "internal_error" });
    await recordEvent(
      "run.failed",
      `Artifact output exceeded ${MAX_OUTPUT_BYTES} bytes`,
      { size: Buffer.byteLength(content, "utf8") },
      "system",
    );
    return { ok: false, run, message: "Artifact output exceeded size cap.", correlationId };
  }

  // Enforce time budget
  if (Date.now() - startMs > timeLimit) {
    await supabase.updateRunStatusInDb(run.id, "timed_out", { failureClassification: "timeout" });
    await recordEvent("run.timed_out", `Run exceeded ${timeLimit}ms budget`, {}, "system");
    return { ok: false, run, message: "Run exceeded time budget.", correlationId };
  }

  // ── Persist private artifact record + storage object ──
  const contentHash = hashString(content);
  const artifactInsert = await supabase.createArtifactInDb({
    workspaceId: task.workspaceId,
    taskId: task.id,
    runId: run.id,
    type: ARTIFACT_KIND,
    displayName: `${task.title} — plan brief v${plan.version}`,
    mediaType: ARTIFACT_MEDIA,
    storageRef: "",
    contentHash,
    sizeBytes: Buffer.byteLength(content, "utf8"),
    state: "draft",
    summary: `Plan brief v${plan.version} generated by ${WORKFLOW_LABEL}.`,
    provenance: {
      workflow: WORKFLOW_ID,
      provider: plan.provider || planner.PLANNER_ID,
      providerLabel: planner.PLANNER_LABEL,
      planId: plan.id,
      planVersion: plan.version,
      planPayloadHash: plan.payloadHash,
      taskId: task.id,
      runId: run.id,
      correlationId,
      generatedBy: actor || "user",
      generatedAt: new Date().toISOString(),
    },
    createdBy: actor || null,
  });
  if (!artifactInsert.ok) {
    await supabase.updateRunStatusInDb(run.id, "failed", { failureClassification: "internal_error" });
    await recordEvent("run.failed", `Artifact insert failed: ${artifactInsert.message}`, {}, "system");
    return { ok: false, run, message: artifactInsert.message, correlationId };
  }
  const artifact = artifactInsert.artifact;

  const safeFilename = `plan-brief-v${plan.version}.md`;
  const upload = await supabase.uploadArtifactFile(
    task.workspaceId,
    artifact.id,
    safeFilename,
    content,
    ARTIFACT_MEDIA,
    Buffer.byteLength(content, "utf8"),
  );
  if (!upload.ok) {
    await supabase.updateRunStatusInDb(run.id, "failed", { failureClassification: "internal_error" });
    await recordEvent("run.failed", `Artifact upload failed: ${upload.message}`, {}, "system");
    return { ok: false, run, artifact, message: upload.message, correlationId };
  }

  // Update artifact with storageRef + state ready
  await supabase.updateArtifactStateInDb(task.workspaceId, artifact.id, "ready");
  // Note: storageRef is the path; we set it on the record for future queries
  // (not currently editable via updateArtifactState, but the path is preserved in the storage layer).

  // 3. artifact ready
  await recordEvent(
    "artifact.ready",
    `Artifact ready (${Buffer.byteLength(content, "utf8")} bytes)`,
    { artifactId: artifact.id, contentHash, sizeBytes: Buffer.byteLength(content, "utf8") },
    "system",
  );

  // 4. mark run succeeded (transition active -> succeeded)
  const finished = await supabase.updateRunStatusInDb(run.id, "succeeded", {
    timeUsedMs: Date.now() - startMs,
    budgetUsed: 0,
  });
  if (!finished.ok) {
    await recordEvent("run.failed", `Finalize failed: ${finished.message}`, {}, "system");
    return { ok: false, run, artifact, message: finished.message, correlationId };
  }

  // 5. run succeeded event
  await recordEvent(
    "run.succeeded",
    `${WORKFLOW_LABEL} completed`,
    { durationMs: Date.now() - startMs, artifactId: artifact.id },
    "system",
  );

  // Update task -> completed (transition running -> completed)
  // Note: the task was already transitioned to queued before the run, and
  // the run is the authoritative state. We leave the task in 'completed'
  // for clean history once a successful run exists.
  await supabase.updateTaskInDb(task.workspaceId, task.id, { status: "completed" });

  // Audit event
  await supabase.createAuditEventInDb({
    workspaceId: task.workspaceId,
    actorId: null,
    actorType: "system",
    action: "workflow.succeeded",
    objectType: "run",
    objectId: run.id,
    metadata: {
      workflow: WORKFLOW_ID,
      artifactId: artifact.id,
      planId: plan.id,
      planVersion: plan.version,
      taskId: task.id,
      durationMs: Date.now() - startMs,
    },
    correlationId,
  });

  return {
    ok: true,
    run: finished.run,
    artifact: { ...artifact, state: "ready", storageRef: upload.path },
    message: `${WORKFLOW_LABEL} complete.`,
    correlationId,
  };
}

module.exports = {
  WORKFLOW_ID,
  WORKFLOW_LABEL,
  ARTIFACT_KIND,
  ARTIFACT_MEDIA,
  MAX_INPUT_BYTES,
  MAX_OUTPUT_BYTES,
  DEFAULT_TIMEOUT_MS,
  newCorrelationId,
  buildBrief,
  validatePlanApproval,
  runSafeWorkflow,
};
